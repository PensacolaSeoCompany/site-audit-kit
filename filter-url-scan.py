# System / analytics / nonce params that use the _underscore shape but are NOT facets.
FILTER_DENY = {'_ga', '_gl', '_hsenc', '_hsmi', '_ke', '_wpnonce', '_thumbnail_id', '_gid',
               '_hjsession', '_branch_match_id', '_ga_', '_fbp'}
PAGE_KEYS = {'page', 'paged', '_paged'}


def is_filter_key(k):
    kl = k.lower()
    if kl in FILTER_DENY:
        return False
    return bool(FILTER_KEYS.match(k))

