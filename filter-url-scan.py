def fetch(url):
    """GET url, return (status, canonical, robots, byte_len) — used for probes."""
    try:
        req = urllib.request.Request(url, headers={'User-Agent': UA})
        r = urllib.request.urlopen(req, timeout=15)
        html = r.read().decode('utf-8', 'replace')
        canon = re.search(r'<link[^>]*rel=["\']canonical["\'][^>]*href=["\']([^"\']+)', html, re.I)
        robots = re.search(r'<meta[^>]*name=["\']robots["\'][^>]*content=["\']([^"\']+)', html, re.I)
        return (r.status, canon.group(1) if canon else '', robots.group(1) if robots else '', len(html))
    except Exception as e:
        return (getattr(e, 'code', None), '', '', 0)


def probe(url):
    st, canon, robots, _ = fetch(url)
    return (st, canon, robots)


def last_linked_page(base_listing, page_hrefs, base_host):
    """Determine REAL linked pagination depth from what the paginator EXPOSES (owner reframe: count
    only linked URLs, don't probe forward indefinitely). Returns (n_pages, unbounded_flag).
    Strategy: (1) the highest page number the pager actually LINKS is the floor; (2) a SHORT bounded
    forward-walk (cap 12) confirms continuity past the linked links without hanging on an unbounded
    ?_paged= pager — the absurd-value probe in main() is what flags true unboundedness."""
    styles_path = any(re.search(r'/page/\d', h or '') for h in page_hrefs)
    styles_param = any(re.search(r'[?&](?:page|paged|_paged)=\d', h or '') for h in page_hrefs)
    if not (styles_path or styles_param):
        return (1, False)
    clean = base_listing.split('?')[0].rstrip('/')
    # (1) highest page number the site LINKS
    linked_max = 1
    for h in page_hrefs:
        m = re.search(r'(?:/page/|[?&](?:page|paged|_paged)=)(\d+)', h or '')
        if m:
            linked_max = max(linked_max, int(m.group(1)))

    def page_url(n):
        if styles_path:
            return f"{clean}/page/{n}/"
        m = re.search(r'[?&](page|paged|_paged)=', ' '.join(h or '' for h in page_hrefs))
        key = m.group(1) if m else 'page'
        return f"{clean}/?{key}={n}"

    # (2) short bounded walk from the linked max to find the natural end (WordPress-style archives
    # link only 1-2 pages but many more exist). Cap 12 fetches so an unbounded ?_paged= never hangs.
    n = max(1, linked_max)
    WALK_CAP = 12
    steps = 0
    while steps < WALK_CAP:
        st, _, robots, _ = fetch(page_url(n + 1))
        if st == 200 and 'noindex' not in (robots or '').lower():
            n += 1
            steps += 1
            continue
        break
    unbounded = (steps >= WALK_CAP)  # never hit a natural end within the cap = likely unbounded
    return (n, unbounded)


def main(urls):
    import kit_env
    (kit_env.KIT_WORK / 'tmp').mkdir(parents=True, exist_ok=True)
    tf = tempfile.NamedTemporaryFile('w', suffix='.cjs', delete=False, dir=kit_env.KIT_WORK / 'tmp')
    tf.write(NODE.replace('__PUPPETEER__', kit_env.puppeteer_require_js())
             .replace('__CHROME__', json.dumps(kit_env.chrome_bin(required=True))))
    tf.close()
    all_params = {}          # param name -> set(values seen)  (single-dimension enumeration)
    combined_keysets = set()  # frozenset of filter keys seen TOGETHER in ONE generated URL
    linked_dims = set()        # filter dimensions that appear in an actual rendered <a href>
    page_hrefs = []
    hreflangs = []
    sample_urls = []         # de-duplicated single-filter URLs to probe
    base_host = urlparse(urls[0]).netloc
    listing0 = urls[0]
    for u in urls:
        env = dict(os.environ, SCAN_UA=UA)
        if not _tx.allowed(u):           # robots.txt (owner safety rule 2026-10-14)
            print(f"FILTER-SCAN: skipped {u} (robots.txt disallows it; not loaded)")
            continue
        _tx.pacer(u).wait()
        try:
            out = subprocess.run(['node', tf.name, u], capture_output=True, text=True,
                                 timeout=180, env=env)
            data = json.loads(out.stdout.strip().splitlines()[-1])
        except Exception:
            continue
        hreflangs += data.get('hreflangs', [])
        page_hrefs += data.get('pageHrefs', [])
        listing_path = urlparse(u).path or '/'
        # SPLIT by crawlability (owner rule §37): Google follows LINKED urls (rendered <a href>),
        # NOT urls that exist only after a user clicks. hrefs/hrefsPost = real anchors (crawlable);
        # clicked/combined/gen = interaction-generated (NOT crawlable unless also linked/shared).
        linked_set = list(data.get('hrefs', [])) + list(data.get('hrefsPost', []))
        interaction_set = (list(data.get('clicked', [])) + list(data.get('combined', []))
                           + list(data.get('gen', [])))
        # track which param keys came from a LINKED anchor vs only from interaction
        for h in linked_set:
            if '?' in (h or ''):
                try:
                    for k in parse_qs(urlparse(h).query):
                        if is_filter_key(k) and k.lower() not in PAGE_KEYS:
                            linked_dims.add(k)
                except Exception:
                    pass
        exposed = linked_set + interaction_set
        for h in exposed:
            if '?' not in (h or ''):
                continue
            try:
                pu = urlparse(h if h.startswith('http') else 'https://' + base_host + '/' + h.lstrip('/'))
            except Exception:
                continue
            qs = parse_qs(pu.query)
            fkeys = [k for k in qs if is_filter_key(k)]
            # NON-page filter keys define the combination dimensions (page is a separate multiplier)
            dim_keys = sorted(k for k in fkeys if k.lower() not in PAGE_KEYS)
            if not fkeys:
                continue
            for k in fkeys:
                all_params.setdefault(k, set()).update(qs[k])
            # record co-occurrence: 2+ DISTINCT filter dimensions in ONE site-generated URL = cross-linked
            if len(dim_keys) >= 2:
                combined_keysets.add(frozenset(dim_keys))
            # build a single-dimension probe sample per filter key
            for k in dim_keys or fkeys:
                one = ((pu.scheme or 'https') + '://' + (pu.netloc or base_host) + pu.path
                       + '?' + urlencode({k: qs[k][0]}, doseq=False))
                if one not in sample_urls:
                    sample_urls.append(one)
        # (a3) FacetWP-style facets: values enumerated from data-value chips grouped by facet name.
        # These are the values the site's OWN UI exposes even when a headless click can't complete
        # the AJAX round-trip that writes the URL. The param is ?<name>=<value> (name already carries
        # its leading _ for FacetWP, e.g. _blog_tags).
        for pname, vals in (data.get('facetValues') or {}).items():
            if not is_filter_key(pname):
                continue
            all_params.setdefault(pname, set()).update(vals)
            if vals:
                one = 'https://' + base_host + listing_path + '?' + urlencode({pname: vals[0]})
                if one not in sample_urls:
                    sample_urls.append(one)
    os.unlink(tf.name)

    if not all_params:
        print("FILTER-SCAN: no filter/facet parameter controls found on the listing page(s)")
        return 0

    # ---- language dimension (locale prefixes) from hreflang alternates on the listing ----
    langs = {h.lower() for h in hreflangs if h and h.lower() != 'x-default'}
    L = max(1, len(langs))

    # ---- pagination dimension from the REAL linked pager (bounded walk) ----
    n_pages, page_unbounded = last_linked_page(listing0, page_hrefs, base_host)

    # ---- combination arithmetic from what the SITE actually links ----
    # dims that co-occur in one generated URL cross-multiply; the rest add.
    dim_sizes = {k: max(1, len(v)) for k, v in all_params.items() if k.lower() not in PAGE_KEYS}
    crossed = set()
    for ks in combined_keysets:
        crossed |= set(ks)
    cross_product = 1
    for k in crossed:
        cross_product *= dim_sizes.get(k, 1)
    # single-filter URLs of the CROSSED dims are also distinct (?cat=X, ?tag=Y on their own)
    single_of_crossed = sum(dim_sizes.get(k, 0) for k in crossed)
    additive = sum(dim_sizes[k] for k in dim_sizes if k not in crossed)
    linked_combos = (cross_product + single_of_crossed if crossed else 0) + additive
    # multiply by real pager pages and languages (both site-exposed multipliers)
    # CRAWLABLE space = only what is LINKED. Facet chips (FacetWP data-value) count as linked
    # (the plugin renders crawlable facet links); pushState-only params do NOT.
    _facet_names = set()
    for _u in urls:
        pass
    # facetValues keys were already added to all_params; treat them as linked (FacetWP links them)
    linked_dim_keys = linked_dims | {k for k in all_params
                                     if k.startswith('_') and k.lower() not in PAGE_KEYS}
    crawlable_filter_dims = {k: dim_sizes[k] for k in dim_sizes if k in linked_dim_keys}
    if crawlable_filter_dims:
        _crossed_here = crossed & set(crawlable_filter_dims)
        _cross = 1
        for k in _crossed_here:
            _cross *= crawlable_filter_dims[k]
        # single-filter URLs of the crossed dims are ALSO distinct real URLs (?cat=X alone,
        # ?tag=Y alone) — add them to the grid, don't absorb them
        _single_crossed = sum(crawlable_filter_dims[k] for k in _crossed_here)
        _add = sum(v for k, v in crawlable_filter_dims.items() if k not in crossed)
        crawlable_combos = (_cross + _single_crossed if _crossed_here else 0) + _add
    else:
        crawlable_combos = 0
    # the number Google can actually reach:
    # TOTAL COMBINATION COUNT = full filter space (cross-product + additive) × pages × languages.
    # This is a property of the URL SPACE and does NOT depend on crawl tier — report it as the
    # number (owner: "how many combinations are there?"). include a per-language breakdown so the
    # cross-product is explicit (e.g. 7 cat + 24 tag + 7×24 combos = 199/lang × 8 langs = 1592).
    # DISTINCT FILTER STATES per language: single-dim URLs + cross-product of co-occurring dims.
    # (linked_combos already = cross_product + additive from the dim_sizes above.)
    per_lang = linked_combos
    filter_combos = per_lang * L                   # distinct filtered views across languages
    # pagination is a SEPARATE, stated multiplier (bounded path pages), not folded in — so the
    # headline count reconciles to a hand count and pagination is reported explicitly.
    exposed_count = filter_combos                  # THE combination count (the owner's question)
    paginated_total = filter_combos * max(1, n_pages)
    interaction_only = 0 if crawlable_combos else exposed_count

    # ---- probe the enumerated single-filter URLs (what the site links) ----
    probed = []
    for su in sample_urls[:4]:
        st, canon, robots = probe(su)
        probed.append((su, st, canon, robots))
    live200 = [x for x in probed if x[1] == 200]

    # ---- SEVERITY MODIFIER: server validation. Probe absurd values (NOT counted). ----
    # A 200 for an invented value = the server accepts arbitrary input, so linked/shared variants
    # beyond our enumeration also resolve. This grades severity; it is NOT the size of the space.
    clean_listing = listing0.split('?')[0].rstrip('/') + '/'
    # absurd FILTER value: reuse a real filter key if we have one (else generic ?category=)
    _fkey = next((k for k in dim_sizes), 'category')
    absurd_val = fetch(clean_listing + '?' + urlencode({_fkey: 'zzznonsense9999xyz'}))
    # absurd PAGE value: use the site's OWN page-param style (FacetWP=_paged, WP=paged/page)
    _pgkey = next((k for k in all_params if k.lower() in PAGE_KEYS),
                  '_paged' if any('facetwp' in (h or '') or '_paged' in (h or '') for h in page_hrefs)
                  else 'page')
    absurd_pg = fetch(clean_listing + '?' + urlencode({_pgkey: '999999'}))
    unvalidated = (absurd_val[0] == 200) or (absurd_pg[0] == 200)
    # QA fix #3: pagination is UNBOUNDED only when an ABSURD page number still 200s. A bounded
    # /page/2/ that 404s past the real end is NORMAL; the count is the real linked depth (n_pages).
    if absurd_pg[0] == 200:
        page_unbounded = True

    # ---- canonical protection: do the param URLs canonical to a CLEAN (param-less) listing? ----
    canon_clean = bool(live200) and all(x[2] and '?' not in x[2] for x in live200)

    # ======================= OUTPUT (prefixes kept for the sidecar) =======================
    print(f"FILTER-SCAN: parameters = {json.dumps({k: len(v) for k, v in all_params.items()})}")
    # FILTER-COMBOS second capture group = the REAL exposed count (linked/generated), not a synthetic floor
    print(f"FILTER-COMBOS: {len(dim_sizes)} filter dimension(s); at least {exposed_count} filter combinations (~{paginated_total} with pagination) "
          f"combination URLs the site itself links or generates")
    for su, st, canon, robots in probed:
        print(f"FILTER-PROBE: {su}  ->  {st}  canonical={canon or 'none'}  robots={robots or 'none'}")

    # FILTER-MATH: parse-friendly arithmetic. Report REAL exposed count + validation as a MODIFIER.
    cross_desc = ('×'.join(f"{k[0].upper()}={dim_sizes[k]}" for k in sorted(crossed))
                  if crossed else 'none')
    parts = []
    for k in sorted(crossed):
        parts.append(f"{k}={dim_sizes[k]}")
    for k in sorted(dim_sizes):
        if k not in crossed:
            parts.append(f"{k}={dim_sizes[k]}(additive)")
    math_dims = ' '.join(parts) if parts else 'none'
    page_desc = (f"page={n_pages}" + ("-UNBOUNDED" if page_unbounded else "-linked"))
    print(f"FILTER-MATH: {math_dims} L={L} {page_desc} "
          f"cross-linked={'yes' if crossed else 'no'} unvalidated={'yes' if unvalidated else 'no'} "
          f"→ exposed(linked/generated)={exposed_count} "
          f"(cross-product {cross_desc}"
          + (f" × L={L}" if L > 1 else "")
          + (f" × page={n_pages}" if n_pages > 1 else "")
          + ")"
          + ("; server validates nothing (?category=nonsense & ?page=999 both 200) — shared/linked "
             "variants beyond these also resolve" if unvalidated else
             "; server validates filter/page values (absurd values 404)"))

    if live200:
        # SEVERITY grades on the CRAWLABLE (linked) set, not what the UI could generate (§37):
        #  - filter dims that appear in real <a href> (or FacetWP facet links) AND self-canonical
        #    /index = HIGH (Google crawls AND indexes a large duplicate space).
        #  - large linked set but canonical-to-clean = MEDIUM (crawled, not indexed as duplicate).
        #  - NO filter dim is linked (only interaction/pushState) = LOW: Google can't reach them;
        #    unvalidated server is a note, not a crawl problem, because nothing links the variants.
        _has_crawlable_filters = bool(crawlable_combos)
        if not _has_crawlable_filters:
            high = False
            _lowtier = True
        else:
            high = not canon_clean          # indexable duplicate space
            _lowtier = False
        token = ("UNBOUNDED-INDEXABLE" if high
                 else "INTERACTION-ONLY" if _lowtier
                 else "CANONICAL-PROTECTED")
        if _lowtier:
            body = (f"the filter controls are <button> elements with no href — navigation is bound "
                    f"in JavaScript, so these ?param= URLs are NOT clean crawlable links and are "
                    f"not in the sitemap. That makes discovery unreliable (Google's renderer can "
                    f"fire interactions but does not dependably follow event-driven controls), and "
                    f"each canonicals to the clean listing. BUT the server validates nothing "
                    f"(?page=999, ?category=nonsense both 200), so any of these variants that gets "
                    f"rendered, shared, or linked from anywhere resolves and can enter the index. "
                    f"Fix both ways: make the filters real <a href> links (so the good ones are "
                    f"reliably found) AND block the parameter space in robots.txt / return 404 for "
                    f"invalid values")
        elif unvalidated and canon_clean:
            body = (f"the site links/generates {exposed_count} filter URLs and the server validates "
                    "nothing — any shared or linked filter/page variant also resolves at 200; each "
                    "canonicals to the clean listing (no duplicate-content harm) but every one is "
                    "still crawled, wasting crawl budget")
        elif not canon_clean:
            body = (f"the site links/generates {exposed_count} filter URLs that self-canonical/index "
                    "— a duplicate URL space Google can index"
                    + ("; the server also validates nothing, so linked/shared variants beyond these "
                       "resolve too" if unvalidated else ""))
        else:
            body = (f"the site links/generates {exposed_count} filter URLs; each canonicals to the "
                    "clean listing (lower duplicate-content risk) but the URLs are still crawlable "
                    "and waste crawl budget")
        print(f"FILTER-VERDICT: {token} ({len(dim_sizes)} filters generate 200-OK URLs; {body})")
    return 0


def index_check(urls, param_names):
    """INDEX CHECK (owner correction, a Shopify store 2026-09-22). Everything above reads the MARKUP
    and robots.txt; none of it says what is IN GOOGLE'S INDEX. I called robots-blocked ?sort_by=
    chip links "harmless"; the owner ran site:host "?sort" and found them indexed. A Disallow
    stops the crawl, so Google never sees the canonical on that URL, and any internal link is
    enough to index the bare address. So: ask Google. site:<host> "?<param>" via SerpAPI for the
    standard parameter families plus every detected filter param; keep ONLY on-site links (deep
    result pages leak off-site URLs); print estimates + distinct on-site parameter URLs.
    Fail-soft: no key / no network -> INDEX-CHECK: skipped (UNKNOWN, never "clean")."""
    from urllib.parse import quote, urlparse as _up
    host = _up(urls[0]).hostname or ""
    host = host[4:] if host.startswith("www.") else host
    key = os.environ.get('SERPAPI_KEY') or os.environ.get('SERP_API_KEY')   # optional; unset = skipped
    if not key:
        print("INDEX-CHECK: skipped (no SerpAPI key) — whether parameter URLs are INDEXED is UNKNOWN")
        return
    fams = ['?sort', '?q=', '?page=', '?filter', 'sort_by'] + [p for p in param_names if p not in ('page', 'q', 'sort_by')]
    seen = {}; ests = {}
    for fam in fams:
        q = f'site:{host} "{fam}"'
        est = None
        for start in (0, 10):
            try:
                u = ('https://serpapi.com/search.json?engine=google&q=' + quote(q)
                     + f'&num=100&start={start}&api_key=' + key)
                d = json.load(urllib.request.urlopen(u, timeout=60))
                est = est if est is not None else (d.get('search_information') or {}).get('total_results')
                res = d.get('organic_results') or []
                if not res:
                    break
                for r in res:
                    l = r.get('link') or ''
                    h = (_up(l).hostname or '')
                    h = h[4:] if h.startswith('www.') else h
                    if h == host and '?' in l:
                        seen.setdefault(l, fam)
            except Exception as e:
                print(f"INDEX-CHECK: {q} -> error {str(e)[:60]}")
                break
        ests[fam] = est
    kinds = {}
    for l in seen:
        qs = l.split('?', 1)[1]
        k = ('sort_by' if 'sort_by' in qs else 'filter' if 'filter.' in qs or qs.startswith('filter') else
             'q=' if qs.startswith('q=') or '&q=' in qs else 'page=' if 'page=' in qs else 'other')
        kinds[k] = kinds.get(k, 0) + 1
    print("INDEX-CHECK: " + " | ".join(f'"{f}" est={ests[f]}' for f in fams))
    print(f"INDEXED-PARAMS: {len(seen)} distinct on-site parameter URL(s) in Google's index "
          f"(kinds {json.dumps(kinds)}; estimates {json.dumps({f: ests[f] for f in fams})})")
    for l in list(seen)[:12]:
        print(f"   INDEXED: {l}")


