"""filter-url-scan.py — detect FACETED / FILTER URL SPACES that a raw-HTML crawl cannot see.
READ-ONLY: this tool only reads (GET/HEAD requests and page loads at most); it never submits a
form, logs in, or changes anything on a site.

WHY (a blog/shop site 2026-08-02, owner: "there are filters that create new URLs"): a blog/shop
listing exposes category/tag/sort/price filters as BUTTONS or JS-injected links that build
`?category=x&tag=y` URLs via pushState. Each combination is a real 200 URL, often index,follow,
and canonical-to-the-clean-listing — a duplicate URL space Google can crawl into. A raw
crawl never sees the controls (they hydrate client-side); the FacetWP detector (a roofing site) only fired
via hack-scan's orphan probe. This renders the listing pages and probes the space directly.

COUNTING DISCIPLINE (owner reframe 2026-08-03): Google does NOT fabricate URLs — it crawls only
what is ACTUALLY EXPOSED: rendered anchors carrying ?params, URLs the filter UI itself generates
(pushState/replaceState + click), and the pagination URLs the paginator LINKS. So the SIZE of the
space is measured from what the site links/generates, NOT by us inventing ?page=999 and counting
200s. The absurd-value probe (?page=999, ?category=nonsense) is KEPT but reclassified as a SEVERITY
MODIFIER — a 200 means the server validates nothing, so any linked/shared variant beyond the
enumerated set also resolves — it is NOT the count and NOT proof the space is crawled.

  - Cross-product vs sum: two dimensions multiply (C×T) ONLY when the site LINKS them combined in a
    single URL (?category=x&tag=y confirmed generated by the UI). Dimensions that never co-occur in
    a generated URL are additive.
  - Language multiplier: locale prefixes (/de/blog/, /fr/blog/ …) detected from hreflang alternates
    on the listing multiply the whole space (each locale carries its own filter UI).
  - Pagination: counted from the REAL linked pages the paginator exposes (follow /page/N until it
    stops), a BOUNDED multiplier — not "infinite" — unless the pager itself links a ?page= param
    with no last page.

Usage: filter-url-scan.py <listing-url> [<listing-url> ...]
Emits FILTER-SCAN / FILTER-COMBOS / FILTER-PROBE / FILTER-VERDICT / FILTER-MATH lines the sidecar
(checks-to-findings.py) turns into a finding.
"""
