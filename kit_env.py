"""Shared paths and tool lookup for the kit's Python scripts (no third-party imports).

KIT_HOME  = the folder this file is in (the repo root); env KIT_HOME is ignored on purpose so a
            stale value cannot point a script at another checkout.
KIT_WORK  = env KIT_WORK, else $KIT_HOME/work (gitignored working data)
  crawl JSON, Lighthouse JSON, findings sidecars -> $KIT_WORK/crawl
  case folders (logs, evidence, site-audit.html) -> $KIT_WORK/cases/<slug>
REPORTS   = $KIT_HOME/reports (publish target)
Chrome    = env CHROME_BIN, else the first of google-chrome, google-chrome-stable, chromium,
            chromium-browser found on PATH.
Node      = modules resolve from $KIT_HOME/node_modules first, then Node's normal lookup.
"""
import os
import shutil
from pathlib import Path

KIT_HOME = Path(__file__).resolve().parent
KIT_WORK = Path(os.environ.get("KIT_WORK") or (KIT_HOME / "work"))
CRAWL_DIR = KIT_WORK / "crawl"
CASES_DIR = KIT_WORK / "cases"
REPORTS_DIR = KIT_HOME / "reports"
NODE_MODULES = KIT_HOME / "node_modules"

# kit-local Node (install.sh puts it in .node/ when the system node is missing or < 20): first on PATH
_LOCAL_NODE_BIN = KIT_HOME / ".node" / "bin"
if (_LOCAL_NODE_BIN / "node").exists() and str(_LOCAL_NODE_BIN) not in os.environ.get("PATH", "").split(os.pathsep):
    os.environ["PATH"] = str(_LOCAL_NODE_BIN) + os.pathsep + os.environ.get("PATH", "")

CHROME_NAMES = ("google-chrome", "google-chrome-stable", "chromium", "chromium-browser")


def chrome_bin(required=False):
    """Path to a Chrome/Chromium binary, or None (or SystemExit when required)."""
    env = os.environ.get("CHROME_BIN")
    if env:
        return env
    rec = KIT_WORK / "chrome-bin"   # written by install.sh
    try:
        first = rec.read_text().strip().splitlines()[0] if rec.is_file() else ""
        if first and os.access(first, os.X_OK):
            return first
    except (OSError, IndexError):
        pass
    for name in CHROME_NAMES:
        p = shutil.which(name)
        if p:
            return p
    for p in sorted(KIT_HOME.glob(".chrome/chrome/linux-*/chrome-linux64/chrome")):
        if os.access(p, os.X_OK):
            return str(p)
    if required:
        raise SystemExit("FATAL: no Chrome found. Install google-chrome or chromium, or set CHROME_BIN.")
    return None


def case_dir(slug):
    return CASES_DIR / slug


def node_env(env=None):
    """Environment for a `node` child: NODE_PATH puts $KIT_HOME/node_modules first."""
    e = dict(os.environ if env is None else env)
    parts = [str(NODE_MODULES)] + [p for p in e.get("NODE_PATH", "").split(os.pathsep) if p]
    e["NODE_PATH"] = os.pathsep.join(parts)
    return e


# JavaScript snippet for node scripts generated by Python: loads puppeteer-core (or puppeteer)
# from $KIT_HOME/node_modules first, then from Node's normal search path.
def puppeteer_require_js():
    nm = str(NODE_MODULES)
    return ("(()=>{const p=require('path');const tries=[p.join(%r,'puppeteer-core'),p.join(%r,'puppeteer'),"
            "'puppeteer-core','puppeteer'];for(const t of tries){try{return require(t);}catch(e){}}"
            "throw new Error('puppeteer-core not found: run npm install in the kit folder');})()" % (nm, nm))
